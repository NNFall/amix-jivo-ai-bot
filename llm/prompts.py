def build_llm_messages(
    *,
    dialog_messages: list[dict[str, Any]],
) -> list[dict[str, Any]]:
    messages: list[dict[str, Any]] = [{"role": "system", "content": SYSTEM_PROMPT}]
    messages.extend(message for message in dialog_messages if message.get("role"))
    return messages
