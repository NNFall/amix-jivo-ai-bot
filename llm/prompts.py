def build_llm_messages(
    *,
    transcript: str,
    customer_text: str,
    product_lookup_result: dict | None = None,
) -> list[dict]:
    messages: list[dict] = [{"role": "system", "content": SYSTEM_PROMPT}]

    if transcript:
        messages.append(
            {
                "role": "user",
                "content": f"История диалога:\n{transcript}",
            }
        )

    if product_lookup_result:
        messages.append(
            {
                "role": "user",
                "content": (
                    "Backend уже выполнил поиск по базе товаров.\n"
                    "Не вызывай search_products повторно, если этого результата достаточно.\n\n"
                    "product_lookup_result:\n"
                    f"{json.dumps(product_lookup_result, ensure_ascii=False)}"
                ),
            }
        )

    messages.append(
        {
            "role": "user",
            "content": f"Последнее сообщение клиента:\n{customer_text}",
        }
    )
    return messages


def build_product_facts_messages(
    *,
    transcript: str,
    customer_text: str,
    product_lookup_result: dict,
    backend_actions: dict | None = None,
) -> list[dict]:
    payload = {
        "customer_text": customer_text,
        "product_lookup_result": product_lookup_result,
        "backend_actions": backend_actions or {},
    }

    return [
        {"role": "system", "content": PRODUCT_FACTS_RESPONSE_PROMPT},
        {
            "role": "user",
            "content": (
                f"История диалога:\n{transcript or 'нет'}\n\n"
                "Данные для ответа:\n"
                f"{json.dumps(payload, ensure_ascii=False)}"
            ),
        },
    ]
