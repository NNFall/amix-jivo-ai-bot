def build_llm_messages(
    *,
    dialog_messages: list[dict[str, Any]] | None = None,
    runtime_context: dict[str, Any] | None = None,
    transcript: str = "",
    customer_text: str = "",
    product_lookup_result: dict | None = None,
) -> list[dict[str, Any]]:
    messages: list[dict[str, Any]] = [{"role": "system", "content": SYSTEM_PROMPT}]
    messages.append(_internal_context_message(runtime_context, product_lookup_result=product_lookup_result))
    messages.extend(_resolve_dialog_messages(dialog_messages, transcript, customer_text))
    return messages


def build_company_faq_messages(*, customer_text: str, safe_answer: str) -> list[dict[str, Any]]:
    return [
        {"role": "system", "content": COMPANY_FAQ_REWRITE_PROMPT},
        {
            "role": "user",
            "content": json.dumps(
                {
                    "message": customer_text,
                    "safe_answer": safe_answer,
                },
                ensure_ascii=False,
            ),
        },
    ]


def build_product_facts_messages(
    *,
    dialog_messages: list[dict[str, Any]] | None = None,
    runtime_context: dict[str, Any] | None = None,
    transcript: str = "",
    customer_text: str = "",
    product_lookup_result: dict,
    backend_actions: dict | None = None,
    include_tool_results_system: bool = True,
) -> list[dict[str, Any]]:
    context = dict(runtime_context or {})
    context.setdefault("type", "amix_internal_context")
    context["backend_actions"] = backend_actions or {}

    messages: list[dict[str, Any]] = [{"role": "system", "content": PRODUCT_FACTS_RESPONSE_PROMPT}]
    messages.append(_internal_context_message(context))
    messages.extend(_resolve_dialog_messages(dialog_messages, transcript, customer_text))
    if include_tool_results_system:
        messages.append(
            {
                "role": "system",
                "content": (
                    "TOOL_RESULTS_JSON:\n"
                    f"{json.dumps({'tool_name': 'search_products', 'mode': 'backend_prelookup', 'result': product_lookup_result}, ensure_ascii=False)}"
                ),
            }
        )
    return messages


def _internal_context_message(
    runtime_context: dict[str, Any] | None,
    *,
    product_lookup_result: dict | None = None,
) -> dict[str, str]:
    context = dict(runtime_context or {})
    context.setdefault("type", "amix_internal_context")
    return {
        "role": "system",
        "content": f"INTERNAL_CONTEXT_JSON:\n{json.dumps(context, ensure_ascii=False, default=str)}",
    }


def _resolve_dialog_messages(
    dialog_messages: list[dict[str, Any]] | None,
    transcript: str,
    customer_text: str,
) -> list[dict[str, Any]]:
    if dialog_messages is not None:
        return [message for message in dialog_messages if message.get("role")]

    messages = _transcript_to_role_messages(transcript)
    customer_text = (customer_text or "").strip()
    if customer_text and not _last_user_message_equals(messages, customer_text):
        messages.append({"role": "user", "content": customer_text})
    return messages


def _transcript_to_role_messages(transcript: str) -> list[dict[str, str]]:
    messages: list[dict[str, str]] = []
    for raw_line in (transcript or "").splitlines():
        line = raw_line.strip()
        if not line:
            continue
        if line.startswith("Клиент:"):
            messages.append({"role": "user", "content": line.removeprefix("Клиент:").strip()})
        elif line.startswith("Бот:"):
            messages.append({"role": "assistant", "content": line.removeprefix("Бот:").strip()})
    return messages


def _last_user_message_equals(messages: list[dict[str, Any]], customer_text: str) -> bool:
    for message in reversed(messages):
        if message.get("role") != "user":
            continue
        return str(message.get("content") or "").strip() == customer_text
    return False
