SYSTEM_PROMPT = """
Ты AI-бот первой линии для AMIX.

Правила:
- отвечай на русском языке;
- не выдумывай товарные факты;
- если фактов о товаре нет в базе, честно скажи об этом;
- если вопрос просит подбор, аналог, совместимость или техническое сравнение, предложи передать вопрос менеджеру;
- отвечай коротко и по делу.
""".strip()


def build_user_prompt(customer_text: str, transcript: str) -> str:
    if transcript:
        return (
            "История диалога:\n"
            f"{transcript}\n\n"
            "Последнее сообщение клиента:\n"
            f"{customer_text}\n\n"
            "Сформируй безопасный ответ без выдумывания фактов."
        )

    return (
        "Последнее сообщение клиента:\n"
        f"{customer_text}\n\n"
        "Сформируй безопасный ответ без выдумывания фактов."
    )
